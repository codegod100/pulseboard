-- The reader's schema on Postgres (Neon), for the FastAPI Cloud server. The
-- same tables and columns as migrations/ (SQLite, D1), so scripts/d1_to_postgres.py
-- copies rows across one for one.
--
-- Times are UTC in `timestamp` columns (no time zone), as SQLite keeps them,
-- so nothing depends on the connection's TimeZone setting.
-- Full-text search is a generated tsvector with a GIN index, in place of FTS5.

CREATE TABLE IF NOT EXISTS users (
  did TEXT PRIMARY KEY,
  indexed_at TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);

CREATE TABLE IF NOT EXISTS web_sessions (
  token TEXT PRIMARY KEY,
  user_did TEXT NOT NULL,
  expires_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_web_sessions_expiry ON web_sessions(expires_at);

CREATE TABLE IF NOT EXISTS oauth_states (
  state TEXT PRIMARY KEY,
  data TEXT NOT NULL,
  expires_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS feeds (
  feed_url TEXT PRIMARY KEY,
  title TEXT,
  site_url TEXT,
  description TEXT,
  feed_type TEXT,
  last_fetched_at TIMESTAMP,
  last_error TEXT,
  subscriber_count INTEGER NOT NULL DEFAULT 0,
  error_count INTEGER NOT NULL DEFAULT 0,
  favicon_url TEXT,
  etag TEXT,
  last_modified TEXT
);

CREATE TABLE IF NOT EXISTS subscriptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_did TEXT NOT NULL,
  feed_url TEXT NOT NULL,
  title TEXT,
  category TEXT,
  added_at TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  UNIQUE(user_did, feed_url)
);
CREATE INDEX IF NOT EXISTS idx_subscriptions_feed_user ON subscriptions(feed_url, user_did);

CREATE TABLE IF NOT EXISTS articles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  feed_url TEXT NOT NULL,
  guid TEXT NOT NULL,
  title TEXT NOT NULL DEFAULT '',
  url TEXT,
  author TEXT,
  summary TEXT,
  content TEXT,
  full_content TEXT,
  published TIMESTAMP,
  updated TIMESTAMP,
  fetched_at TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  search TSVECTOR GENERATED ALWAYS AS (
    setweight(to_tsvector('english', coalesce(title, '')), 'A') ||
    setweight(to_tsvector('english', coalesce(author, '')), 'B') ||
    setweight(to_tsvector('english', coalesce(summary, '')), 'C') ||
    setweight(to_tsvector('english', coalesce(content, '')), 'D')
  ) STORED,
  UNIQUE(feed_url, guid)
);
CREATE INDEX IF NOT EXISTS idx_articles_url ON articles(url);
CREATE INDEX IF NOT EXISTS idx_articles_feed_published ON articles(feed_url, published);
CREATE INDEX IF NOT EXISTS idx_articles_search ON articles USING GIN (search);

CREATE TABLE IF NOT EXISTS read_state (
  user_did TEXT NOT NULL,
  article_id BIGINT NOT NULL,
  is_read INTEGER NOT NULL DEFAULT 0,
  read_at TIMESTAMP,
  PRIMARY KEY (user_did, article_id)
);

CREATE TABLE IF NOT EXISTS read_state_history (
  user_did TEXT NOT NULL,
  feed_url TEXT NOT NULL,
  guid TEXT NOT NULL,
  is_read INTEGER NOT NULL DEFAULT 0,
  read_at TIMESTAMP,
  PRIMARY KEY (user_did, feed_url, guid)
);
